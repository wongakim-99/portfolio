// 한국어 줄바꿈 다듬기. 화면 폭이 바뀌어도 '볼 / 수 있습니다', '이 / 글', 'P = / NP' 처럼 어색하게 끊기지 않게
// 붙어 다녀야 하는 낱말 사이 띄어쓰기를 줄바꿈 없는 공백(U+00A0)으로 바꿈. 화면에 그리는 글에만 씀
const NBSP = ' ';

export function keepPhrases(text: string): string {
  return (
    text
      // 의존 명사는 앞뒤 낱말과 같이: 볼 수 있습니다, 부탁할 수도 있습니다, 할 것 같은, 그럴 줄 몰랐
      .replace(/ (수|것|줄)([도는가]?) /g, `${NBSP}$1$2${NBSP}`)
      // 보조 용언은 앞 낱말과 같이: 읽어 보고, 증명해 주세요, 적어 두면
      .replace(/([어아해여]) (보|봐|봤|주|줘|줬|두|놓)(?=\S)/g, `$1${NBSP}$2`)
      // 한 글자 관형사는 뒤 낱말과 같이: 이 글, 그 문제, 한 번, 두 개
      .replace(/(^|\s)(이|그|저|한|두|세|몇|첫|새|각) (?=\S)/g, `$1$2${NBSP}`)
      // 수식은 한 덩어리로: P = NP, 1 + 1 = 2
      .replace(/ ([=+≠<>]) /g, `${NBSP}$1${NBSP}`)
  );
}
